#!/usr/bin/env python3
"""
Build DOOM2D: the bootable ATR (boot loader + XEX + the levels + save area)
in bin/.

Usage:
    python build_doom2d.py [map1.map map2.map ...]
With no maps: every maps/d2d_map*.map (the original Doom 2D levels, in order).

Steps: maps -> data/*.lvl (tools/map2bin.py), pass 1 with placeholder
sectors: boot loader and two XEX (VBXE registers at $D600 / $D700, the boot
loader picks by $D740), ATR (the sectors -> source/gen/); pass 2 the same
with the real sectors, the final ATR.
"""

import glob
import math
import os
import struct
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
MADS = os.path.join(ROOT, 'mads.exe')
SRC = os.path.join(ROOT, 'source')
GEN = os.path.join(SRC, 'gen')
OUT = os.path.join(ROOT, 'bin')
SECTOR = 128
SAVE_SLOT_MAX = 128             # sectors a save slot (source/savegame.asm asserts it fits)

sys.path.insert(0, os.path.join(ROOT, 'tools'))
import map2bin                  # noqa: E402


def mads(src, out, listing=False, page=0xD6):
    args = [MADS, src, f'-o:{out}', f'-d:VBXE_PAGE={page}']
    if listing:
        args += [f'-l:{os.path.join(OUT, "doom2d.lst")}', f'-t:{os.path.join(OUT, "doom2d.lab")}']
    r = subprocess.run(args, cwd=SRC)
    if r.returncode:
        sys.exit(f'{os.path.basename(src)} BUILD FAILED!')


def write_layout(starts, save_sector, n_levels, d7_sector):
    """source/gen: the save area and level count, the $D700 XEX's first
    sector (boot loader), the levels' first sectors."""
    with open(os.path.join(GEN, 'atr_layout_const.asm'), 'w') as f:
        f.write("; Auto-generated by build_doom2d.py - DO NOT EDIT\n")
        f.write(f"SAVE_SEC1 = {save_sector}\nLVL_COUNT = {n_levels}\n"
                f"XEX_D7_SEC = {d7_sector}\n")
    with open(os.path.join(GEN, 'atr_levels.asm'), 'w') as f:
        f.write("; Auto-generated by build_doom2d.py - DO NOT EDIT\n")
        f.write("lvl_sec_lo  dta " + ','.join(str(s & 255) for s in starts) + "\n")
        f.write("lvl_sec_hi  dta " + ','.join(str(s >> 8) for s in starts) + "\n")


def make_atr(atr_path, boot, xex, xex7, lvl_files):
    """Boot sectors 1-3, the $D600 XEX from 4, the $D700 XEX, the levels
    (each its own size), then 3 save slots. Returns the levels' first
    sectors, the save sector and the $D700 XEX's first sector."""
    if len(boot) > 3 * SECTOR:
        sys.exit(f'boot loader too large ({len(boot)} B)')
    xex6_sectors = math.ceil(len(xex) / SECTOR)
    d7 = 4 + xex6_sectors
    xex_sectors = xex6_sectors + math.ceil(len(xex7) / SECTOR)
    levels = bytearray()
    starts = []
    for path in lvl_files:
        data = open(path, 'rb').read()
        if len(data) % SECTOR:
            sys.exit(f'{path} is not whole sectors')
        starts.append(4 + xex_sectors + len(levels) // SECTOR)
        levels += data
    save = 4 + xex_sectors + len(levels) // SECTOR
    total = max(3 + xex_sectors + len(levels) // SECTOR + 3 * SAVE_SLOT_MAX, 720)
    disk = bytearray(total * SECTOR)
    disk[:len(boot)] = boot
    disk[3 * SECTOR:3 * SECTOR + len(xex)] = xex
    disk[(d7 - 1) * SECTOR:(d7 - 1) * SECTOR + len(xex7)] = xex7
    disk[(3 + xex_sectors) * SECTOR:(3 + xex_sectors) * SECTOR + len(levels)] = levels
    para = total * SECTOR // 16
    header = struct.pack('<HHHB9x', 0x0296, para & 0xFFFF, SECTOR, para >> 16)
    with open(atr_path, 'wb') as f:
        f.write(header + disk)
    print(f"  ATR: {atr_path} ({16 + len(disk)} bytes, {total} sectors): XEX {xex6_sectors} "
          f"+ $D700 XEX from {d7}, levels {len(levels) // SECTOR} from "
          f"{starts[0] if starts else 0}, save {save}")
    return starts, save, d7


def main():
    maps = sys.argv[1:] or sorted(glob.glob(os.path.join(ROOT, 'maps', 'd2d_map*.map')))
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(GEN, exist_ok=True)

    print("Converting maps...")
    lvl_files = []
    for m in maps:
        base = os.path.splitext(os.path.basename(m))[0]
        out = os.path.join(ROOT, 'data', base)
        map2bin.convert_map(m, out + '.bin', out + '.ent')     # -> .lvl
        lvl_files.append(out + '.lvl')

    xex_path = os.path.join(OUT, 'doom2d.xex')
    xex7_path = os.path.join(OUT, 'doom2d_d7.xex')

    def build(listing):
        """The boot loader and both XEX for the layout in source/gen."""
        boot_xex = os.path.join(OUT, 'boot.xex')
        mads('bootloader.asm', boot_xex)
        boot = open(boot_xex, 'rb').read()[6:]
        os.remove(boot_xex)                 # the ATR is the only output
        mads('main.asm', xex_path, listing=listing)
        mads('main.asm', xex7_path, page=0xD7)
        return boot, open(xex_path, 'rb').read(), open(xex7_path, 'rb').read()

    # pass 1: placeholder sectors (the same sizes as the real ones)
    print("Building boot loader + XEX $D600 / $D700 (pass 1)...")
    write_layout([0] * len(lvl_files), 9999, len(lvl_files), 9999)
    starts, save, d7 = make_atr(os.path.join(OUT, 'doom2d.atr'), *build(False), lvl_files)

    print("Rebuilding (pass 2, the real sectors)...")
    write_layout(starts, save, len(lvl_files), d7)
    layout2 = make_atr(os.path.join(OUT, 'doom2d.atr'), *build(True), lvl_files)
    if layout2 != (starts, save, d7):
        sys.exit('the XEX changed size between the passes')
    for p in (xex_path, xex7_path):
        r = subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'check_xex.py'), p])
        if r.returncode:
            sys.exit('check_xex.py FAILED')
        os.remove(p)                        # the ATR is the only output
    print(f"\n=== DONE ===\nBoot from: {os.path.join('bin', 'doom2d.atr')}")


if __name__ == '__main__':
    main()
